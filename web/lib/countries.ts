export function foldText(value: string): string {
  return value
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/['’]/g, "")
    .replace(/[^a-z0-9]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

export function displayCountry(key: string): string {
  const fixed = DISPLAY_FIXES[key];
  if (fixed) return fixed;
  const small = new Set(["and", "of", "the"]);
  return key
    .split(" ")
    .map((word, index) => (small.has(word) && index > 0 ? word : word.charAt(0).toUpperCase() + word.slice(1)))
    .join(" ");
}

function canonCountry(value: string): string | null {
  const key = foldText(value);
  if (!key || NOT_COUNTRIES.has(key)) return null;
  if (COUNTRY_ALIAS[key]) return COUNTRY_ALIAS[key];
  if (key.length > 3 && !/^\d+$/.test(key)) return key;
  return null;
}

/** Countries named in a field, in order, without duplicates. */
export function countryKeys(value: string | null | undefined): string[] {
  if (!value || !value.trim()) return [];
  const parts = value.split(",").map((part) => part.trim()).filter(Boolean);
  const keys: string[] = [];
  const add = (key: string | null) => {
    if (key && !keys.includes(key)) keys.push(key);
  };
  if (parts.length <= 1) {
    add(canonCountry(value));
    return keys;
  }
  for (const part of parts) add(canonCountry(part));
  if (keys.length === 0) add(canonCountry(value));
  return keys;
}

export function formatCountries(value: string | null | undefined): string | null {
  const keys = countryKeys(value);
  if (keys.length === 0) return null;
  return keys.map(displayCountry).join(", ");
}
